export { cn } from "cn"

/** Links built from collected data only open http(s) URLs; anything else (javascript:, data:) becomes inert. */
export function safeHref(url: string | null | undefined): string | undefined {
  if (!url) return undefined;
  try {
    const u = new URL(url);
    return u.protocol === "http:" || u.protocol === "https:" ? u.href : undefined;
  } catch {
    return undefined;
  }
}
